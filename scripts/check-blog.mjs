import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { blogEntries, publishedBlogEntries, dateISO } from '../src/lib/blog-content.mjs';
import { floorRelated } from '../src/lib/floor-content.mjs';
import { SITE } from '../src/lib/floor-seo.mjs';
const read = url => readFileSync(`dist${url}/index.html`, 'utf8');
const escape = value => value.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const index = read('/blog');
const home = read('/');
const navigation = home.match(/<nav\b[^>]*aria-label="Основна навигация"[^>]*>[\s\S]*?<\/nav>/)?.[0];
assert(navigation?.includes('Блог и съвети'), 'Homepage must clearly name the blog menu');
assert.equal((navigation.match(/href="\/blog"/g) || []).length, 2, 'Desktop and mobile menus must both link to the blog');
assert(navigation.includes('Всички статии'));
const footer = home.match(/<footer\b[\s\S]*?<\/footer>/)?.[0];
assert(footer?.includes('href="/blog"'), 'Homepage footer must link to the canonical blog');
const sitemap = readFileSync('dist/sitemap.xml','utf8');
assert(!existsSync('dist/blog/_shablon/index.html'), 'Author template must not be published');
assert(!index.includes('<astro-island'), 'Blog index must be prerendered');
assert.equal(publishedBlogEntries.length, 4);
let lastPosition = -1;
for (const entry of publishedBlogEntries) {
 assert(index.includes(escape(entry.data.title)) && index.includes(`href="${entry.url}"`));
 const position = index.indexOf(`href="${entry.url}"`);assert(position > lastPosition, 'Newest articles must be first');lastPosition = position;
 assert(sitemap.includes(`<loc>${SITE}${entry.url}</loc>`));
 const html = read(entry.url);
 assert(!html.includes('<astro-island'), `${entry.id}: no React hydration`);
 assert.equal((html.match(/<h1\b/g)||[]).length, 1);
 assert(html.includes(escape(entry.data.title)) && html.includes(escape(entry.data.description)));
 assert(html.includes(`rel="canonical" href="${SITE}${entry.url}"`));
 assert(html.includes(`datetime="${dateISO(entry.data.pubDate)}"`));
 for (const [,heading] of entry.body.matchAll(/^#{2,3} (.+)$/gm)) assert(html.includes(escape(heading.trim())), `${entry.id}: missing authored section`);
 for (const faq of entry.data.faqs || []) assert(html.includes(escape(faq.q)) && html.includes(escape(faq.a)));
 assert.equal((html.match(/<details class="home-faq"/g)||[]).length, entry.data.faqs?.length || 0);
 for (const link of floorRelated(entry.data.related)) assert(html.includes(`href="${link.url}"`) && existsSync(`dist${link.url}/index.html`));
 if (entry.image) assert(html.includes(entry.image.src) && existsSync('public'+entry.image.src));
 const graph = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
 const posting = graph.find(node => node['@type'] === 'BlogPosting');
 assert(posting && posting.headline === entry.data.title);
 assert.equal(posting.datePublished, dateISO(entry.data.pubDate));
 assert.equal(posting.dateModified, dateISO(entry.data.updatedDate || entry.data.pubDate));
 assert.equal(graph.find(node=>node['@type']==='FAQPage').mainEntity.length, entry.data.faqs.length);
 const og = html.match(/property="og:image" content="([^"]+)"/);assert(og && existsSync('public'+new URL(og[1]).pathname));
 assert(html.includes('property="og:image:width" content="1200"'));
}
assert(blogEntries.every(entry => !entry.id.split('/')[1].startsWith('_')));
const redirects = JSON.parse(readFileSync('vercel.json','utf8')).redirects;
assert(redirects.some(rule => rule.source === '/blogove' && rule.destination === '/blog' && rule.statusCode === 301));
console.log('Blog checks passed: 4 Markdown articles, dates, archive order, media fallback, FAQ, related links, BlogPosting, sitemap and zero hydration.');
